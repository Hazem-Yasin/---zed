// Draws the "زد" wordmark as vector paths from Amiri Bold, so the logo never depends on a font loading.
// Writes: src/components/ui/logoPath.ts (used by <Logo/>) and public/quran-icon.svg (favicon, PWA icon, splash).
//   node scripts/generate-logo.mjs
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const buf = readFileSync('node_modules/@fontsource/amiri/files/amiri-arabic-700-normal.woff');
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Both letters are right-joining only, so "زد" is two isolated glyphs. Lay out right-to-left by hand.
const zay = font.charToGlyph('ز');
const dal = font.charToGlyph('د');
const SIZE = 100;
const scale = SIZE / font.unitsPerEm;
const dalPath = dal.getPath(0, 0, SIZE);
const zayPath = zay.getPath(dal.advanceWidth * scale, 0, SIZE);

const boxes = [dalPath.getBoundingBox(), zayPath.getBoundingBox()];
const bb = {
  x1: Math.min(...boxes.map((b) => b.x1)),
  y1: Math.min(...boxes.map((b) => b.y1)),
  x2: Math.max(...boxes.map((b) => b.x2)),
  y2: Math.max(...boxes.map((b) => b.y2)),
};
const w = bb.x2 - bb.x1;
const h = bb.y2 - bb.y1;

// Fit into the 48x48 tile with padding, centred.
const TILE = 48;
const target = 25;
const k = Math.min(target / w, target / h);
const tx = (TILE - w * k) / 2 - bb.x1 * k;
const ty = (TILE - h * k) / 2 - bb.y1 * k + 0.5;

const toD = (p) => p.toPathData(2);
const d = `${toD(dalPath)}${toD(zayPath)}`;
const transform = `translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${k.toFixed(4)})`;

writeFileSync(
  'src/components/ui/logoPath.ts',
  `// Generated by scripts/generate-logo.mjs. Do not edit by hand.\nexport const ZAD_PATH = ${JSON.stringify(d)};\nexport const ZAD_TRANSFORM = ${JSON.stringify(transform)};\n`
);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" fill="none">
  <defs>
    <linearGradient id="g" x1="6" y1="4" x2="42" y2="44" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#d97706"/>
      <stop offset="1" stop-color="#fbbf24"/>
    </linearGradient>
  </defs>
  <rect x="1" y="1" width="46" height="46" rx="13" fill="url(#g)"/>
  <path transform="${transform}" fill="#0f172a" d="${d}"/>
</svg>
`;
writeFileSync('public/quran-icon.svg', svg);
console.log('logo written', { w: w.toFixed(1), h: h.toFixed(1), k: k.toFixed(3) });
